// Simple confetti burst — no external dependency needed
function fireConfetti() {
  try {
    const canvas = document.createElement('canvas');
    canvas.style.cssText = 'position:fixed;inset:0;width:100vw;height:100vh;pointer-events:none;z-index:9999';
    document.body.appendChild(canvas);
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
    const ctx = canvas.getContext('2d');
    const pieces = Array.from({ length: 90 }, () => ({
      x: Math.random() * canvas.width,
      y: Math.random() * canvas.height * 0.4,
      r: Math.random() * 7 + 4,
      color: ['#6366f1','#8b5cf6','#06b6d4','#10b981','#f59e0b','#ec4899'][Math.floor(Math.random() * 6)],
      vx: (Math.random() - 0.5) * 6,
      vy: Math.random() * 3 + 2,
      alpha: 1,
    }));
    let raf;
    function draw() {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      pieces.forEach(p => {
        ctx.globalAlpha = p.alpha;
        ctx.fillStyle = p.color;
        ctx.beginPath();
        ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
        ctx.fill();
        p.x += p.vx; p.y += p.vy; p.vy += 0.12; p.alpha -= 0.012;
      });
      if (pieces.some(p => p.alpha > 0)) raf = requestAnimationFrame(draw);
      else { document.body.removeChild(canvas); cancelAnimationFrame(raf); }
    }
    draw();
  } catch (_) {}
}


